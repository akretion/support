import json
import logging

from odoo import _, api, fields, models, tools
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)

NEXT_VERSION = "next"
SUPPORTED_ENVIRONMENTS = ("preprod", "prod")


class SupportRelease(models.Model):
    _name = "support.release"
    _description = "Support Release"
    _rec_name = "version"
    _order = "create_date, id"

    version = fields.Char(
        required=True,
        index=True,
        help="Version of the deployment, or 'next' while no version is defined.",
    )
    tickets = fields.Char(
        help="JSON list of the ticket ids shipped by this release.",
    )
    is_sent = fields.Boolean(
        default=False,
        copy=False,
        help="Set once the support server has accepted the release.",
    )

    _sql_constraints = [
        (
            "version_uniq",
            "unique(version)",
            "A release already exists for this version.",
        ),
    ]

    @api.model
    def _get_environment(self):
        """Return the deployment environment, or False when releases stay silent."""
        running_env = tools.config.get("running_env")
        return running_env if running_env in SUPPORTED_ENVIRONMENTS else False

    @api.model
    def _normalize_version(self, version):
        version = (version or "").strip()
        if version.lower() == NEXT_VERSION:
            return NEXT_VERSION
        return version

    @api.model
    def _normalize_tickets(self, tickets):
        normalized = set()
        for ticket in tickets or ():
            try:
                normalized.add(int(ticket))
            except (TypeError, ValueError):
                _logger.warning("Ignoring non integer ticket reference %r", ticket)
        return sorted(normalized)

    def _get_ticket_ids(self):
        self.ensure_one()
        return json.loads(self.tickets or "[]")

    @api.model
    def _register_deployment(self, version, tickets=None):
        """Record a deployment of a release.

        Called from the migration generated by the project pipeline. The version
        is the key of the release: registering the same version twice merges the
        tickets instead of creating a second release.
        """
        version = self._normalize_version(version)
        if not version:
            _logger.warning("Release registration without version, ignored")
            return self.browse()
        ticket_ids = self._normalize_tickets(tickets)
        release = self.search([("version", "=", version)])
        if release:
            merged = sorted(set(release._get_ticket_ids()) | set(ticket_ids))
            if merged != release._get_ticket_ids():
                release.tickets = json.dumps(merged)
        else:
            release = self.create(
                {"version": version, "tickets": json.dumps(ticket_ids)}
            )
        if version != NEXT_VERSION:
            release._absorb_next_release()
        return release

    def _absorb_next_release(self):
        """Merge the pending 'next' release into this one, then drop it."""
        self.ensure_one()
        if self.version == NEXT_VERSION:
            return
        next_release = self.search([("version", "=", NEXT_VERSION)])
        if not next_release:
            return
        merged = sorted(
            set(next_release._get_ticket_ids()) | set(self._get_ticket_ids())
        )
        self.tickets = json.dumps(merged)
        next_release.unlink()

    @api.model
    def _next_release_to_send(self):
        return self.search([("is_sent", "=", False)], limit=1)

    def _build_payload(self):
        self.ensure_one()
        return {
            "environment": self._get_environment(),
            "version": self.version,
            "tickets": self._get_ticket_ids(),
        }

    def _push(self):
        self.ensure_one()
        server = self.env.ref("support.support_server", raise_if_not_found=False)
        if not server:
            raise UserError(_("The support server is not configured."))
        server.sudo()._request("POST", "/release", data=self._build_payload())
        self.is_sent = True

    @api.model
    def _cron_push_releases(self):
        """Push the oldest pending release, one per cron run."""
        if not self._get_environment():
            return
        release = self._next_release_to_send()
        if not release:
            return
        try:
            with self.env.cr.savepoint():
                release._push()
        except Exception:
            _logger.exception("Unable to push release %s", release.version)

    def action_push_pending(self):
        """Push every pending release, one request per release."""
        if not self._get_environment():
            raise UserError(
                _("Releases are only pushed from a preprod or prod environment.")
            )
        for _counter in range(100):
            release = self._next_release_to_send()
            if not release:
                break
            try:
                with self.env.cr.savepoint():
                    release._push()
            except Exception:
                _logger.exception("Unable to push release %s", release.version)
                break
        return True
